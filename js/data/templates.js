const MONTHS_GEN = ['января','февраля','марта','апреля','мая','июня','июля','августа','сентября','октября','ноября','декабря'];

export function dateRu(isoDate) {
  if (!isoDate) return '«___» __________ 20__ г.';
  const [y, m, d] = isoDate.split('-').map(Number);
  return `«${String(d).padStart(2, '0')}» ${MONTHS_GEN[m - 1]} ${y} г.`;
}
const today = () => new Date().toISOString().slice(0, 10);
const money = (v) => {
  const n = Number(String(v ?? '').replace(/[^\d.,]/g, '').replace(',', '.')) || 0;
  return n.toLocaleString('ru-RU', { minimumFractionDigits: 2, maximumFractionDigits: 2 }).replace(/ /g, ' ');
};
const num = (v) => Number(String(v ?? '').replace(/[^\d.,]/g, '').replace(',', '.')) || 0;
const or = (v, dflt = '________________') => (String(v ?? '').trim() || dflt);
const signer = (s) => (String(s ?? '').trim() ? `, в лице ${s.trim()}` : '');

