export const findArticle = (id) => ARTICLES.find((a) => a.id === id);

export function searchArticles(query, cat = 'all') {
  const q = query.trim().toLowerCase();
  return ARTICLES.filter((a) => (cat === 'all' || a.cat === cat) && (!q ||
    [a.title, a.summary, a.refs, ...a.steps.flatMap((s) => [s.title, s.text])].join(' ').toLowerCase().includes(q)));
}
